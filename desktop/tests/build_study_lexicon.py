"""Regenerate the bundled pronunciations for the fixed question bank.

Usage: ESPEAK_DATA_PATH=/path/containing/espeak-ng-data \
  python tests/build_study_lexicon.py /path/to/espeak-ng
The phonemizer is a development-time tool, not linked into the application.
"""
from html.parser import HTMLParser
from pathlib import Path
import os
import re
import subprocess
import sys


class Bank(HTMLParser):
    def __init__(self):
        super().__init__()
        self.depth = 0
        self.text = []

    def handle_starttag(self, tag, attrs):
        if self.depth:
            self.depth += 1
        elif dict(attrs).get('class') == 'question' or tag == 'strong':
            self.depth = 1

    def handle_endtag(self, tag):
        if self.depth:
            self.depth -= 1

    def handle_data(self, data):
        if self.depth:
            self.text.append(data)


root = Path(__file__).resolve().parents[1]
bank = Bank()
bank.feed((root / 'ui/index.html').read_text())
words = set(re.findall(r"[a-z]+(?:'[a-z]+)*", ' '.join(bank.text).lower().replace('\u2019', "'")))
words.update('abcdefghijklmnopqrstuvwxyz')
words.update('zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen twenty thirty forty fifty sixty seventy eighty ninety hundred thousand million billion point minus plus times divided by per percent equals less than greater degrees ohms micro and hertz kilohertz megahertz gigahertz decibels volts amperes watts milliwatts kilowatts millivolts metres centimetres millimetres'.split())
words = sorted(words)
command = [sys.argv[1], '-v', 'en-us', '-q', '--ipa']
if os.environ.get('ESPEAK_DATA_PATH'):
    command += ['--path=' + os.environ['ESPEAK_DATA_PATH']]
result = subprocess.run(command, input='\n'.join(words) + '\n', text=True, capture_output=True, check=True)
lines = [line.strip() for line in result.stdout.splitlines() if line.strip()]
assert len(lines) == len(words), (len(lines), len(words), result.stderr)
output = ['# Pronunciations for Ham Study question-bank vocabulary.',
          '# Generated by tests/build_study_lexicon.py using eSpeak NG (English US).',
          '# Phonetic data only; no phonemizer code is linked into the app.']
for word, phones in zip(words, lines):
    # Both ONNX tokenizers use Unicode IPA codepoints, not eSpeak mnemonics.
    phones = ' '.join(c for c in phones if not c.isspace() and c not in '\u200d\u200c')
    output.append(word + ' || ' + phones)
path = root / 'src-tauri/speech/study-lexicon.txt'
path.parent.mkdir(parents=True, exist_ok=True)
path.write_text('\n'.join(output) + '\n')
print(f'Wrote {len(words)} entries to {path}')
